#!/usr/bin/env python3
"""Generates src/net/trust_anchors.c: BearSSL trust anchors (root CAs) for HTTPS.

Source: the Mozilla root store as shipped by Debian/Ubuntu's ca-certificates
package (/usr/share/ca-certificates/mozilla/*.crt). Locally added CAs
(/usr/local/share/ca-certificates) are deliberately NOT included.
Usage: python3 tools/gen_trust_anchors.py [CERT_DIR]
"""
import base64, glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CERT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/ca-certificates/mozilla"

def tlv(b, i):
    """returns (tag, start of value, end of value, end of element)"""
    tag = b[i]; l = b[i + 1]; j = i + 2
    if l & 0x80:
        n = l & 0x7F; l = int.from_bytes(b[j:j + n], "big"); j += n
    return tag, j, j + l, j + l

def children(b, s, e):
    out = []
    while s < e:
        t, vs, ve, nxt = tlv(b, s); out.append((t, s, vs, ve)); s = nxt
    return out

def oid(b):
    vals = []; v = 0
    for x in b:
        v = (v << 7) | (x & 0x7F)
        if not x & 0x80: vals.append(v); v = 0
    first = vals[0]
    return ".".join(map(str, [first // 40, first % 40] + vals[1:]))

CURVES = {"1.2.840.10045.3.1.7": "BR_EC_secp256r1", "1.3.132.0.34": "BR_EC_secp384r1", "1.3.132.0.35": "BR_EC_secp521r1"}

def parse(der):
    _, s, e, _ = tlv(der, 0)                       # Certificate
    tbs = children(der, s, e)[0]
    f = children(der, tbs[2], tbs[3])
    if f[0][0] == 0xA0: f = f[1:]                    # explicit version
    subject = f[4]; spki = f[5]
    dn = der[subject[1]:subject[3]]
    alg, key = children(der, spki[2], spki[3])
    algf = children(der, alg[2], alg[3])
    a_oid = oid(der[algf[0][2]:algf[0][3]])
    bits = der[key[2] + 1:key[3]]                    # skip the unused-bits byte
    if a_oid == "1.2.840.113549.1.1.1":
        _, s2, e2, _ = tlv(bits, 0)
        n, ex = children(bits, s2, e2)
        nb = bits[n[2]:n[3]].lstrip(b"\0"); eb = bits[ex[2]:ex[3]].lstrip(b"\0")
        return dn, ("rsa", nb, eb)
    if a_oid == "1.2.840.10045.2.1":
        curve = CURVES.get(oid(der[algf[1][2]:algf[1][3]]))
        if not curve: return None
        return dn, ("ec", curve, bits)
    return None

def carr(name, b):
    lines = ", ".join(f"0x{x:02X}" for x in b)
    return f"static const unsigned char {name}[] = {{ {lines} }};\n"

def main():
    files = sorted(glob.glob(os.path.join(CERT_DIR, "*.crt")))
    out = ['/* Generated by tools/gen_trust_anchors.py from the Mozilla root store',
           f' * ({len(files)} files in {CERT_DIR}). Do not edit. */',
           '#include "bearssl.h"', '']
    tas = []
    for k, fn in enumerate(files):
        pem = open(fn).read()
        if "BEGIN CERTIFICATE" not in pem: continue
        b64 = pem.split("-----BEGIN CERTIFICATE-----")[1].split("-----END CERTIFICATE-----")[0]
        r = parse(base64.b64decode("".join(b64.split())))
        if not r: print("skipped (unsupported key):", os.path.basename(fn)); continue
        dn, key = r
        out.append(f"/* {os.path.basename(fn)[:-4]} */")
        out.append(carr(f"TA{k}_DN", dn))
        if key[0] == "rsa":
            out.append(carr(f"TA{k}_N", key[1])); out.append(carr(f"TA{k}_E", key[2]))
            tas.append(f"    {{ {{ (unsigned char *)TA{k}_DN, sizeof TA{k}_DN }}, BR_X509_TA_CA, {{ BR_KEYTYPE_RSA, {{ .rsa = {{ (unsigned char *)TA{k}_N, sizeof TA{k}_N, (unsigned char *)TA{k}_E, sizeof TA{k}_E }} }} }} }},")
        else:
            out.append(carr(f"TA{k}_Q", key[2]))
            tas.append(f"    {{ {{ (unsigned char *)TA{k}_DN, sizeof TA{k}_DN }}, BR_X509_TA_CA, {{ BR_KEYTYPE_EC, {{ .ec = {{ {key[1]}, (unsigned char *)TA{k}_Q, sizeof TA{k}_Q }} }} }} }},")
    out.append("const br_x509_trust_anchor builtin_tas[] = {")
    out += tas
    out.append("};")
    out.append(f"const unsigned builtin_tas_num = {len(tas)};")
    path = os.path.join(ROOT, "src/net/trust_anchors.c")
    open(path, "w").write("\n".join(out) + "\n")
    print(f"{len(tas)} trust anchors -> {path}")

if __name__ == "__main__":
    main()
