#!/usr/bin/env python3
"""Generate src/win32/d3d10_methods.h from mingw-w64's d3d10.h and dxgi.h: for
each COM interface THE WRLD OS implements, the methods in vtable order and how
many arguments each takes after `this` (x86 COM methods are __stdcall, so even
a stub must remove the right number of bytes from the stack).

    python3 tools/gen_d3d10.py [/usr/share/mingw-w64/include]
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INC = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/mingw-w64/include"
IFACES = {
    "dxgi.h": ["IDXGISwapChain", "IDXGIFactory", "IDXGIAdapter", "IDXGIDevice"],
    "d3d10.h": ["ID3D10Device", "ID3D10Buffer", "ID3D10Texture2D", "ID3D10RenderTargetView",
                "ID3D10DepthStencilView", "ID3D10ShaderResourceView", "ID3D10VertexShader",
                "ID3D10PixelShader", "ID3D10GeometryShader", "ID3D10InputLayout", "ID3D10SamplerState",
                "ID3D10RasterizerState", "ID3D10DepthStencilState", "ID3D10BlendState"],
}
out = ["/* generated by tools/gen_d3d10.py from mingw-w64's d3d10.h and dxgi.h - do not edit",
       " * M(interface, index, method, arguments after this) */"]
for hdr, names in IFACES.items():
    text = open(os.path.join(INC, hdr)).read()
    for iface in names:
        m = re.search(r"typedef struct %sVtbl \{(.*?)\} %sVtbl;" % (iface, iface), text, re.S)
        if not m:
            sys.exit("interface %s not found" % iface)
        methods = re.findall(r"\(STDMETHODCALLTYPE \*(\w+)\)\((.*?)\);", m.group(1), re.S)
        for i, (name, args) in enumerate(methods):
            n = args.count(",")              # parameters after This
            out.append("M(%s, %d, %s, %d)" % (iface, i, name, n))
        out.append("#define %s_COUNT %d" % (iface.upper(), len(methods)))
open(os.path.join(ROOT, "src/win32/d3d10_methods.h"), "w").write("\n".join(out) + "\n")
print("ok")
