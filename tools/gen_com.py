#!/usr/bin/env python3
"""Generate a COM method table from a mingw-w64 header: for each interface, its methods in
vtable order and how many arguments each takes after `this` (on x86 COM methods are
__stdcall, so even an unimplemented method must take the right number).

    python3 tools/gen_com.py HEADER OUTPUT INTERFACE...
e.g. tools/gen_com.py /usr/share/mingw-w64/include/d3d8.h src/win32/d3d8_methods.h IDirect3D8 ...
"""
import re, sys

hdr, outp, ifaces = sys.argv[1], sys.argv[2], sys.argv[3:]
text = open(hdr).read()
out = ["/* generated by tools/gen_com.py from mingw-w64's %s - do not edit" % hdr.split('/')[-1],
       " * M(interface, index, method, arguments after this) */"]
for iface in ifaces:
    m = re.search(r"DECLARE_INTERFACE_\(%s,\s*\w+\)\s*\{(.*?)\n\};" % iface, text, re.S)
    if not m:
        sys.exit("interface %s not found" % iface)
    methods = re.findall(r"STDMETHOD_?\((?:[^,()]+,\s*)?(\w+)\s*\)\s*\((.*?)\)\s*PURE;", m.group(1), re.S)
    for i, (name, args) in enumerate(methods):
        args = " ".join(args.split())
        rest = args[len("THIS_"):] if args.startswith("THIS_") else ("" if args == "THIS" else args)
        n = rest.count(",") + 1 if rest.strip() else 0
        out.append("M(%s, %d, %s, %d)" % (iface, i, name, n))
    out.append("#define %s_COUNT %d" % (iface.upper(), len(methods)))
open(outp, "w").write("\n".join(out) + "\n")
