#!/usr/bin/env python3
"""Generate src/win32/d3d9_methods.h from mingw-w64's d3d9.h: for each COM
interface THE WRLD OS implements, the methods in vtable order and how many
arguments each takes after `this`. On x86 COM methods are __stdcall, so the
callee removes its arguments from the stack: even a method that is not
implemented must be a function with the right number of them.

    python3 tools/gen_d3d9.py [/usr/share/mingw-w64/include/d3d9.h]
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HDR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/mingw-w64/include/d3d9.h"
IFACES = ["IDirect3D9", "IDirect3DDevice9", "IDirect3DTexture9", "IDirect3DVertexBuffer9",
          "IDirect3DIndexBuffer9", "IDirect3DSurface9"]

text = open(HDR).read()
out = ["/* generated by tools/gen_d3d9.py from mingw-w64's d3d9.h - do not edit",
       " * M(interface, index, method, arguments after this) */"]
for iface in IFACES:
    m = re.search(r"DECLARE_INTERFACE_\(%s,\s*\w+\)\s*\{(.*?)\n\};" % iface, text, re.S)
    if not m:
        sys.exit("interface %s not found" % iface)
    body = m.group(1)
    methods = re.findall(r"STDMETHOD_?\((?:[^,()]+,\s*)?(\w+)\)\s*\((.*?)\)\s*PURE;", body, re.S)
    for i, (name, args) in enumerate(methods):
        args = " ".join(args.split())
        if args in ("THIS", ""):
            n = 0
        else:
            rest = args[len("THIS_"):] if args.startswith("THIS_") else args
            n = rest.count(",") + 1 if rest.strip() else 0
        out.append("M(%s, %d, %s, %d)" % (iface, i, name, n))
    out.append("#define %s_COUNT %d" % (iface.upper(), len(methods)))
open(os.path.join(ROOT, "src/win32/d3d9_methods.h"), "w").write("\n".join(out) + "\n")
print("%d interfaces" % len(IFACES))
