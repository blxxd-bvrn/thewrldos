#!/usr/bin/env python3
"""Generates src/tls/root_certs.c: the root certificates HTTPS trusts.

Source: the Mozilla root store as shipped by Debian/Ubuntu's ca-certificates
package (/usr/share/ca-certificates/mozilla/*.crt). Locally added CAs
(/usr/local/share/ca-certificates) are deliberately NOT included.
Each certificate is stored as DER together with the position of its subject
name, so the TLS glue can find a server's issuer without parsing every root.
Usage: python3 tools/gen_root_certs.py [CERT_DIR]
"""
import base64, glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CERT_DIR = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/ca-certificates/mozilla"

def tlv(b, i):
    """returns (tag, start of value, end of value) of the element at i"""
    tag = b[i]; l = b[i + 1]; j = i + 2
    if l & 0x80:
        n = l & 0x7F; l = int.from_bytes(b[j:j + n], "big"); j += n
    return tag, j, j + l

def subject_span(der):
    _, s, _ = tlv(der, 0)                      # Certificate
    _, p, _ = tlv(der, s)                      # TBSCertificate
    if der[p] == 0xA0: p = tlv(der, p)[2]      # [0] version
    for _ in range(4):                         # serial, signature, issuer, validity
        p = tlv(der, p)[2]
    _, vs, ve = tlv(der, p)                    # subject
    return p, ve - p

def main():
    certs = []
    for path in sorted(glob.glob(os.path.join(CERT_DIR, "*.crt"))):
        text = open(path).read()
        body = text.split("-----BEGIN CERTIFICATE-----")[1].split("-----END CERTIFICATE-----")[0]
        der = base64.b64decode("".join(body.split()))
        certs.append((os.path.basename(path)[:-4], der))
    out = ["/* Generated by tools/gen_root_certs.py from the Mozilla root store",
           " * (%d certificates). Do not edit. */" % len(certs),
           "#include <stdint.h>",
           "const unsigned char wrld_root_der[] = {"]
    index, off = [], 0
    for name, der in certs:
        so, sl = subject_span(der)
        index.append((off, len(der), off + so, sl, name))
        out.append("    /* %s */" % name.replace("*/", "* /"))
        for i in range(0, len(der), 20):
            out.append("    " + ", ".join("0x%02x" % b for b in der[i:i + 20]) + ",")
        off += len(der)
    out.append("};")
    out.append("const struct { uint32_t off, len, subj_off, subj_len; } wrld_roots[] = {")
    for o, l, so, sl, name in index:
        out.append("    { %d, %d, %d, %d }," % (o, l, so, sl))
    out.append("};")
    out.append("const unsigned wrld_root_count = %d;" % len(certs))
    path = os.path.join(ROOT, "src/tls/root_certs.c")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote %s: %d certificates, %d bytes" % (path, len(certs), off))

main()
